"""Packs every exported asset into one FBX for a single Studio import, plus
orientation markers and a Luau manifest the game reads.

    python combine.py -- <out_fbx> <out_luau> <asset_dir> [<asset_dir> ...]
"""

import glob
import json
import os
import sys

import bpy
import addon_utils

args = sys.argv[sys.argv.index("--") + 1:]
out_fbx, out_luau, dirs = args[0], args[1], args[2:]

bpy.ops.wm.read_factory_settings(use_empty=True)
manifest = {}
for d in dirs:
    manifest.update(json.load(open(os.path.join(d, "manifest.json"))))
    for f in sorted(glob.glob(os.path.join(d, "*.fbx"))):
        bpy.ops.import_scene.fbx(filepath=f)

# Average glow colour per asset from the baked texture, for Roblox Neon.
for name in list(manifest):
    glow = bpy.data.objects.get(name + "_Glow")
    if glow and glow.data.materials:
        img = None
        for n in glow.data.materials[0].node_tree.nodes:
            if n.type == "TEX_IMAGE" and n.image:
                img = n.image
        if img:
            px = list(img.pixels)
            r = g = b = cnt = 0
            for i in range(0, len(px), 4 * 7):
                if px[i + 3] > 0.5 and (px[i] + px[i + 1] + px[i + 2]) > 0.3:
                    r += px[i]; g += px[i + 1]; b += px[i + 2]; cnt += 1
            if cnt:
                manifest[name]["glow"] = [round(r / cnt * 255), round(g / cnt * 255), round(b / cnt * 255)]

# Orientation markers: origin, 5 units forward (-Y) and 5 units up (+Z).
for marker, loc in (("ArtOrigin", (0, 0, 0)), ("ArtForward", (0, -5, 0)), ("ArtUp", (0, 0, 5))):
    bpy.ops.mesh.primitive_cube_add(size=0.1, location=loc)
    bpy.context.active_object.name = marker

for o in bpy.context.scene.objects:
    o.select_set(o.type == "MESH")
bpy.ops.export_scene.fbx(
    filepath=out_fbx, use_selection=True, object_types={"MESH"}, apply_unit_scale=True,
    apply_scale_options="FBX_SCALE_ALL", axis_forward="-Z", axis_up="Y", mesh_smooth_type="FACE",
    path_mode="COPY", embed_textures=True, bake_space_transform=True,
)
names = sorted(o.name for o in bpy.context.scene.objects if o.type == "MESH")
print("PACKED", len(names), "meshes:", ", ".join(names))

# Luau manifest
lines = ["-- Generated by art/tools/combine.py. Heights are in Blender units;", "-- the loader scales from these.", "return {"]
for name in sorted(manifest):
    m = manifest[name]
    glow = m.get("glow")
    glow_s = f", Glow = Color3.fromRGB({glow[0]}, {glow[1]}, {glow[2]})" if glow else ""
    lines.append(f"\t{name} = {{ Height = {m['height']}{glow_s} }},")
lines.append("}")
open(out_luau, "w").write("\n".join(lines) + "\n")
